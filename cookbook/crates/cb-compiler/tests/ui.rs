//! UI golden tests: each `tests/ui/*.peb` is compiled and its rendered
//! diagnostics compared with the `.stderr` next to it. `BLESS=1 cargo test` rewrites them.

mod common;
use common::*;
use pebble::diag::{self, RenderOptions, codes::CODES};
use pebble::sema::CheckOptions;
use pebble::source::SourceFile;

fn render_case(path: &std::path::Path) -> String {
    let text = std::fs::read_to_string(path).unwrap();
    let name = path.file_name().unwrap().to_string_lossy().to_string();
    let opts = CheckOptions {
        warn_shadow: text.lines().any(|l| l.trim() == "//@ warn-shadow"),
    };
    let file = SourceFile::new(name, text);
    let an = pebble::analyze(&file.text, &opts);
    diag::render_all(&an.diagnostics, &file, &RenderOptions::default())
}

#[test]
fn ui_golden() {
    let dir = manifest_dir().join("tests/ui");
    let files = files_with_ext(&dir, "peb");
    assert!(
        files.len() >= 70,
        "need at least 70 UI cases, found {}",
        files.len()
    );
    let failures = big_stack(move || {
        let mut failures = Vec::new();
        for f in files {
            let out = render_case(&f);
            expect_file(&f.with_extension("stderr"), &out, &mut failures);
        }
        failures
    });
    assert!(
        failures.is_empty(),
        "{} UI mismatches (BLESS=1 to update):\n{}",
        failures.len(),
        failures.join("\n")
    );
}

fn all_stderr() -> String {
    let dir = manifest_dir().join("tests/ui");
    files_with_ext(&dir, "stderr")
        .iter()
        .map(|p| std::fs::read_to_string(p).unwrap_or_default())
        .collect::<Vec<_>>()
        .join("\n")
}

#[test]
fn every_code_has_a_ui_case() {
    let all = all_stderr();
    let missing: Vec<&str> = CODES
        .iter()
        .map(|c| c.code)
        .filter(|c| !all.contains(&format!("[{c}]")))
        .collect();
    assert!(missing.is_empty(), "codes without a UI test: {missing:?}");
    assert!(CODES.len() >= 40);
}

#[test]
fn every_code_used_in_sources_is_catalogued() {
    let mut used = Vec::new();
    fn scan(dir: &std::path::Path, used: &mut Vec<String>) {
        for e in std::fs::read_dir(dir).unwrap().flatten() {
            let p = e.path();
            if p.is_dir() {
                scan(&p, used);
            } else if p.extension().is_some_and(|x| x == "rs") && !p.ends_with("codes.rs") {
                let s = std::fs::read_to_string(&p).unwrap();
                let b = s.as_bytes();
                for i in 0..b.len().saturating_sub(5) {
                    if b[i] == b'"'
                        && (b[i + 1] == b'E' || b[i + 1] == b'W')
                        && b[i + 2..i + 6].iter().all(|c| c.is_ascii_digit())
                        && b.get(i + 6) == Some(&b'"')
                    {
                        used.push(s[i + 1..i + 6].to_string());
                    }
                }
            }
        }
    }
    scan(&manifest_dir().join("src"), &mut used);
    assert!(used.len() > 40);
    for u in used {
        assert!(
            CODES.iter().any(|c| c.code == u),
            "code {u} used in source but not in CODES"
        );
    }
}

/// `docs/ERRORS.md` is generated from the catalogue plus the first UI case per code.
fn generate_errors_md() -> String {
    let dir = manifest_dir().join("tests/ui");
    let cases: Vec<(String, String, String)> = files_with_ext(&dir, "peb")
        .into_iter()
        .map(|p| {
            let src = std::fs::read_to_string(&p).unwrap();
            let err = std::fs::read_to_string(p.with_extension("stderr")).unwrap_or_default();
            (
                p.file_name().unwrap().to_string_lossy().to_string(),
                src,
                err,
            )
        })
        .collect();
    let mut out = String::from(
        "# PEBBLE diagnostic catalogue\n\nGenerated by `BLESS=1 cargo test -p cb-compiler --test ui` from `src/diag/codes.rs` and the golden cases in `tests/ui/`. Do not edit by hand.\n\nEach entry shows a minimal program and the exact output of `pebblec check`.\n",
    );
    for c in CODES {
        out.push_str(&format!(
            "\n## {} - {}\n\n{}\n",
            c.code, c.title, c.explanation
        ));
        if let Some((name, src, err)) = cases
            .iter()
            .find(|(_, _, e)| e.contains(&format!("[{}]", c.code)))
        {
            out.push_str(&format!(
                "\nExample (`tests/ui/{name}`):\n\n```text\n{}```\n\n```text\n{}```\n",
                src, err
            ));
        }
    }
    out
}

#[test]
fn errors_md_is_current() {
    let path = manifest_dir().join("docs/ERRORS.md");
    let want = generate_errors_md();
    if bless() {
        std::fs::write(&path, want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "docs/ERRORS.md is stale: run `BLESS=1 cargo test -p cb-compiler --test ui`"
    );
}

#[test]
fn json_output_is_well_formed() {
    let file = SourceFile::new("t.peb", "fn main() { let x: int = true; }");
    let an = pebble::analyze(&file.text, &CheckOptions::default());
    let j = diag::to_json_array(&an.diagnostics, &file);
    assert!(j.contains("\"code\":\"E0301\""), "{j}");
    assert!(j.contains("\"utf16_column\""));
}

#[test]
fn machine_applicable_suggestions_apply() {
    let src = "fn main() { let mut x = 1\n println(to_str(x)); }";
    let an = pebble::analyze(src, &CheckOptions::default());
    let fixed = diag::apply_suggestions(src, &an.diagnostics);
    assert_eq!(fixed, "fn main() { let x = 1;\n println(to_str(x)); }");
    assert!(!pebble::analyze(&fixed, &CheckOptions::default()).has_errors());
}

#[test]
fn color_output_contains_ansi() {
    let file = SourceFile::new("t.peb", "fn main() { let x: int = true; }");
    let an = pebble::analyze(&file.text, &CheckOptions::default());
    let s = diag::render_all(&an.diagnostics, &file, &RenderOptions { color: true });
    assert!(s.contains("\x1b[1;31m"));
}
