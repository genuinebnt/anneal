use solution::*;

#[test]
fn leb_classic() {
    check!(r#"the textbook example"#, read_u32(&[0xE5, 0x8E, 0x26, 0xFF]), Ok((624485, 3)));
}

#[test]
fn leb_padded_is_legal() {
    check!(r#"80 00 is 0"#, read_u32(&[0x80, 0x00, 0x7F]), Ok((0, 2)));
}

#[test]
fn decode_add_module() {
    check!(r#"the classic add(i32, i32)"#, { let m = decode(&[0x00, 0x61, 0x73, 0x6D, 0x01, 0x00, 0x00, 0x00, 0x01, 0x07, 0x01, 0x60, 0x02, 0x7F, 0x7F, 0x01, 0x7F, 0x03, 0x02, 0x01, 0x00, 0x07, 0x07, 0x01, 0x03, 0x61, 0x64, 0x64, 0x00, 0x00, 0x0A, 0x09, 0x01, 0x07, 0x00, 0x20, 0x00, 0x20, 0x01, 0x6A, 0x0B]).unwrap(); (m.types, m.funcs, m.exports, m.bodies) }, (vec![FuncType { params: vec![0x7F, 0x7F], results: vec![0x7F] }], vec![0], vec![Export { name: "add".to_string(), kind: 0, index: 0 }], vec![Body { locals: vec![], code: vec![0x20, 0x00, 0x20, 0x01, 0x6A, 0x0B] }]));
}

#[test]
fn header_only() {
    check!(r#"an empty module"#, decode(&[0x00, 0x61, 0x73, 0x6D, 0x01, 0x00, 0x00, 0x00]), Ok(Module::default()));
}

#[test]
fn bad_magic() {
    check!(r#"not wasm"#, decode(&[0x00, 0x61, 0x73, 0x78, 0x01, 0x00, 0x00, 0x00]), Err(DecodeError::BadMagic));
}

#[test]
fn bad_version() {
    check!(r#"version 2"#, decode(&[0x00, 0x61, 0x73, 0x6D, 0x02, 0x00, 0x00, 0x00]), Err(DecodeError::BadVersion));
}

#[test]
fn section_runs_past_the_end() {
    check!(r#"size says 7, one byte left"#, decode(&[0x00, 0x61, 0x73, 0x6D, 0x01, 0x00, 0x00, 0x00, 0x01, 0x07, 0x01]), Err(DecodeError::Truncated));
}
