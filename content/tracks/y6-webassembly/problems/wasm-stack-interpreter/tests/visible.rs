    check!(r#"local.get 0, local.get 1, i32.add"#, run(&[Func { params: 2, results: 1, locals: 0, code: vec![0x20, 0x00, 0x20, 0x01, 0x6A, 0x0B] }], 0, &[2, 3], 100000), Ok(vec![5]));
