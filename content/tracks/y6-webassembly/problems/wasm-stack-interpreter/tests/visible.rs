#[test]
fn constants() {
    check!(r#"positive and negative i32.const"#, (run(&[Func { params: 0, results: 1, locals: 0, code: vec![0x41, 0x2A, 0x0B] }], 0, &[], 100000), run(&[Func { params: 0, results: 1, locals: 0, code: vec![0x41, 0x7F, 0x0B] }], 0, &[], 100000)), (Ok(vec![42]), Ok(vec![-1])));
}

